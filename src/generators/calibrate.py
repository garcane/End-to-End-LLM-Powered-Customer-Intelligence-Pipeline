"""Measure the IBM Telco seed and write the calibration used by the generator.

    python -m src.generators.calibrate

Reads the extended IBM Cognos workbooks, writes ``data/seed/ibm_calibration.json`` and
renders ``docs/ibm-telco-calibration.md`` so the numbers behind the generator are
reviewable without running any code.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from . import config
from .ibm_seed import (
    ANALOGUE_MAP,
    PROFESSIONAL_AGE_WEIGHTING,
    IbmCalibration,
    find_source_dir,
    load_calibration,
)

REPORT_PATH = config.PROJECT_ROOT / "docs" / "ibm-telco-calibration.md"

#: Where the generator's churn coefficients come from.
COEFFICIENT_PROVENANCE = {
    "inactive_90_days": ("Data Recomendations.md", "No IBM analogue: the seed has no activity history"),
    "negative_feedback": ("Data Recomendations.md", "IBM Satisfaction Score is leaked and cannot be used"),
    "failed_payment": ("Data Recomendations.md", "No clean IBM analogue"),
    "no_event_attendance": ("Data Recomendations.md", "No IBM analogue: the seed has no events"),
    "declining_logins": ("Data Recomendations.md", "No IBM analogue: the seed is cross-sectional"),
    "completed_learning": ("Data Recomendations.md", "No IBM analogue"),
    "attended_first_90_days": ("Data Recomendations.md", "No IBM analogue"),
    "auto_renewal": ("Data Recomendations.md", "Corroborated by IBM: auto_payment"),
    "long_tenure": ("Data Recomendations.md", "Corroborated by IBM: long_tenure"),
    "low_campaign_engagement": ("Domain judgement, reduced", "IBM offer take-up showed no effect"),
    "fee_increase": ("Estimated from IBM", "high_charge"),
    "student_to_full_transition": ("Domain judgement", "No IBM analogue"),
    "multi_service_user": ("Estimated from IBM", "multi_service"),
    "no_recent_advocacy": ("Estimated from IBM", "referred (sign inverted)"),
}


def render_report(cal: IbmCalibration) -> str:
    L: list[str] = []
    a = L.append

    a("# IBM Telco calibration report")
    a("")
    a("Generated by `python -m src.generators.calibrate`. This is the evidence base for")
    a("the member dimension, and for the three churn-model coefficients that are estimated")
    a("from it rather than asserted.")
    a("")
    a(f"- **Source:** `{cal.source}`")
    a(f"- **Rows measured:** {cal.n_source_rows:,}")
    a("")
    for note in cal.notes:
        a(f"> {note}")
        a("")

    a("---")
    a("")
    a("## 1. Leakage audit")
    a("")
    if not cal.leakage:
        a("No leaked columns detected.")
    else:
        a("The extended IBM sample contains two columns that were assigned **after** the")
        a("churn outcome was known. Using either as a predictor would produce a model with")
        a("near-perfect accuracy and no real-world value, so both are excluded from the")
        a("analogue fit. Only their marginal distributions are carried over.")
        a("")
        a("| Column | Verdict | Evidence |")
        a("| --- | --- | --- |")
        for col, finding in cal.leakage.items():
            verdict = finding.get("verdict", "inspected")
            detail = finding.get("detail", "")
            if "class_overlap_points" in finding:
                overlap = finding["class_overlap_points"]
                extra = f"classes overlap by only {overlap:.0f} points on a 5-96 scale"
                detail = f"{detail}; {extra}" if detail else extra
            a(f"| `{col}` | **{verdict}** | {detail} |")
    a("")

    a("## 2. Tenure")
    a("")
    a(f"- Mean **{cal.tenure_mean_months:.2f}** months, sd **{cal.tenure_sd_months:.2f}**")
    a(f"- Censored at **{cal.tenure_max_months} months**: the source covers a fixed observation")
    a("  window, so the true tenure tail is unobservable.")
    a(f"- Deciles: {', '.join(f'{v:g}' for v in cal.tenure_deciles)}")
    a("")
    a("The generator bootstraps from this empirical distribution rather than fitting a")
    a("parametric curve, then stretches it by 1.6x because annual membership terms are")
    a("not month-to-month telco contracts, and extends the tail beyond the censoring")
    a("point for legacy members.")
    a("")

    a("## 3. Demographics")
    a("")
    a("IBM records exact age, so the age bands are measured rather than assumed. The")
    a("adjustment column reflects that membership of a professional body concentrates in")
    a("working years, whereas the seed is a general consumer base. It is the single")
    a("demographic judgement in the calibration and is shown here so it can be reviewed.")
    a("")
    a("| Age band | IBM measured | Weighting | Used by the generator |")
    a("| --- | ---: | ---: | ---: |")
    for band in cal.age_shares_raw:
        raw = cal.age_shares_raw[band]
        adj = cal.age_shares_adjusted.get(band, 0.0)
        w = PROFESSIONAL_AGE_WEIGHTING.get(band, 1.0)
        a(f"| {band} | {raw:.1%} | x{w:.2f} | {adj:.1%} |")
    a("")
    a("**Not carried over:** gender, marital status, dependants, city, zip code, latitude,")
    a("longitude and zip-level population. The geography is US-specific and irrelevant to")
    a("a UK-centred membership body; the personal attributes are sensitive and add nothing")
    a("to an engagement or retention model.")
    a("")

    a("## 4. Commercial behaviour")
    a("")
    a("| Quantity | Measured | Used for |")
    a("| --- | ---: | --- |")
    a(f"| Month-to-month contract share | {cal.month_to_month_share:.1%} | Base rate for `auto_renewal = False` |")
    a(f"| Automatic payment share | {cal.automatic_payment_share:.1%} | Cross-check on the same |")
    a(f"| _-- payment method source_ | | `{cal.payment_method_source}` |")
    a(f"| Paperless billing share | {cal.paperless_billing_share:.1%} | Base rate for `communication_consent` |")
    a(f"| Overall churn rate | {cal.churn_rate:.1%} | Sense-check on cumulative lapse rate |")
    a(f"| Recent joiner share | {cal.joined_share:.1%} | Share of members inside their first year |")
    a(f"| Charge ratio, churned/retained | {cal.churn_charge_ratio:.3f} | Evidence for the fee-sensitivity term |")
    a(f"| Lifetime value, mean | {cal.cltv_mean:,.0f} | Reference only (see below) |")
    a(f"| Lifetime value, coeff. of variation | {cal.cltv_cv:.3f} | Reference only |")
    a(f"| Lifetime value ratio, churned/retained | {cal.cltv_churn_ratio:.3f} | Confirms lapsing members are worth less |")
    a("")
    a("IBM's `CLTV` is a **bounded index** (2,003-6,500), not a currency amount, so its")
    a("scale and spread are not transferred. `model_predictions.predicted_lifetime_value`")
    a("is a genuine revenue figure -- annual fee x expected remaining years x contribution")
    a("margin -- and is deliberately more dispersed than the index. Only the direction of")
    a("the churned/retained ratio carries over.")
    a("")

    a("### A trap in the extended workbook")
    a("")
    a("The extended sample relabels the original four payment methods into three, and the")
    a("relabelling is **lossy**. Every manual `Electronic check` customer -- a third of the")
    a("sample -- is folded into `Bank Withdrawal` alongside genuine automatic payers:")
    a("")
    a("```text")
    a("original                      ->  extended")
    a("Bank transfer (automatic) 21.9%    Bank Withdrawal 55.5%")
    a("Electronic check          33.6%  /")
    a("Credit card (automatic)   21.6%    Credit Card     39.0%")
    a("Mailed check              22.9%  /  Mailed Check     5.5%")
    a("```")
    a("")
    a("Taken at face value the extended labels put the automatic share at **95.6%** rather")
    a("than **43.5%**, and mis-specify the predictor that maps onto `auto_renewal`. The")
    a("calibration therefore reads payment method from the original workbook, where the")
    a("`(automatic)` marker survives. Correcting this moved the fitted coefficient from")
    a("-0.43 to **-0.53**, which is a near-exact match for the -0.50 published in")
    a("`Data Recomendations.md`.")
    a("")

    a("## 5. Advocacy")
    a("")
    a(f"- **{cal.referrer_share:.1%}** of customers referred at least one other customer.")
    a(f"- Among those who did, the mean was **{cal.referrals_mean_among_referrers:.2f}** referrals (max {cal.referrals_max}).")
    a(f"- Churned customers made **{cal.referrals_churn_ratio:.2f}x** as many referrals as retained ones.")
    a("")
    a("That last figure is one of the strongest signals in the seed, and it has no")
    a("counterpart anywhere in the original table list. It is why the generator adds a")
    a("`member_referrals` table and a `no_recent_advocacy` term to the churn model.")
    a("")

    a("## 6. Satisfaction distribution")
    a("")
    a("| Score | Share |")
    a("| ---: | ---: |")
    for score in sorted(cal.satisfaction_shares):
        a(f"| {score} | {cal.satisfaction_shares[score]:.1%} |")
    a("")
    a("Used only as a target for the marginal distribution of `member_feedback.rating`.")
    a("The *conditional* relationship with churn is discarded, because it is leaked.")
    a("")

    a("## 7. Churn reasons")
    a("")
    a("| IBM category | Share of churners |")
    a("| --- | ---: |")
    for cat, share in sorted(cal.churn_category_shares.items(), key=lambda kv: -kv[1]):
        a(f"| {cat} | {share:.1%} |")
    a("")
    a("The generator adopts the **two-level structure** (category then specific reason)")
    a("but not these weights: a professional body loses far fewer members to a direct")
    a("competitor than a telco does, and far more to cost and non-use. The membership")
    a("weights are a documented domain judgement in `config.CHURN_CATEGORIES`.")
    a("")
    a(f"Mean tenure at churn varies by only **{cal.reason_tenure_spread_months:.1f} months** across the five")
    a("categories, so the generator keeps reason only weakly conditional on behaviour")
    a("rather than making it a strong function of it.")
    a("")

    a("## 8. Analogue churn model")
    a("")
    a("Fitted on the comparable sub-population: customers with internet service")
    a(f"(n = {cal.analogue_n:,}, churn rate {cal.analogue_churn_rate:.1%}). Phone-only customers are excluded")
    a("because they hold a structurally different product; including them inverts the sign")
    a("on service breadth, since a cheap single-product customer is not the same thing as a")
    a("disengaged one.")
    a("")
    a(f"In-sample AUC **{cal.analogue_auc:.3f}**.")
    a("")
    a("| IBM predictor | Coefficient | Membership feature | Mapping |")
    a("| --- | ---: | --- | --- |")
    for name, coef in cal.analogue_coefficients.items():
        if name == "intercept":
            a(f"| _intercept_ | {coef:+.3f} | - | - |")
            continue
        target, description = ANALOGUE_MAP.get(name, (None, ""))
        target_txt = f"`{target}`" if target else "_none_"
        a(f"| `{name}` | {coef:+.3f} | {target_txt} | {description} |")
    a("")

    a("## 9. Where each churn coefficient comes from")
    a("")
    a("| Membership feature | Value | Provenance | Note |")
    a("| --- | ---: | --- | --- |")
    for name, value in config.CHURN_COEFFICIENTS.items():
        if name == "intercept":
            continue
        provenance, note = COEFFICIENT_PROVENANCE.get(name, ("-", ""))
        a(f"| `{name}` | {value:+.2f} | {provenance} | {note} |")
    a("")
    a("The nine coefficients published in `Data Recomendations.md` are used exactly as")
    a("specified. Two of them -- `auto_renewal` and `long_tenure` -- are independently")
    a("corroborated by the IBM fit. The extension terms that the recommendation did not")
    a("specify are now estimated from the seed rather than asserted.")
    a("")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Calibrate the generator against the IBM Telco seed.")
    p.add_argument("--no-refresh", action="store_true", help="use the cached calibration instead of re-measuring")
    p.add_argument("--report", type=Path, default=REPORT_PATH, help="path for the markdown report")
    args = p.parse_args(argv)

    source = find_source_dir()
    if source is None and not args.no_refresh:
        print("No IBM workbooks found. Searched:")
        from .ibm_seed import SOURCE_DIRS

        for d in SOURCE_DIRS:
            print(f"  {d}")
        print("\nFalling back to published marginals.")

    cal = load_calibration(verbose=True, refresh=not args.no_refresh)

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(render_report(cal), encoding="utf-8")
    print(f"  wrote {args.report}")

    print("\nAnalogue model (leak-free):")
    for name, coef in cal.analogue_coefficients.items():
        print(f"  {name:<18}{coef:+.3f}")
    print(f"  AUC {cal.analogue_auc:.3f} on {cal.analogue_n:,} rows")
    if cal.leakage:
        print("\nLeakage detected and excluded: " + ", ".join(cal.leakage))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
